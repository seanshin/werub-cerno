def headers(uid: str) -> dict:
    key = os.environ["CERNO_API_KEY"]
    exp = int(time.time()) + 50
    sig = hmac.new(key.encode(), f"{uid}.clinician.{exp}".encode(),
                   hashlib.sha256).hexdigest()
    return {"Content-Type": "application/json", "X-Cerno-User": uid,
            "X-Cerno-Role": "clinician", "X-Cerno-Exp": str(exp), "X-Cerno-Sig": sig}


def post(path: str, body: dict, uid: str = UID) -> tuple[int, dict]:
    req = urllib.request.Request(BASE + path, method="POST",
                                 data=json.dumps(body).encode(), headers=headers(uid))
    try:
        r = urllib.request.urlopen(req, timeout=120)
        return r.status, json.loads(r.read())
    except urllib.error.HTTPError as e:
        return e.code, json.loads(e.read() or b"{}")


